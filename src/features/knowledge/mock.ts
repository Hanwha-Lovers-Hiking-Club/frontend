export function queryMockCards({ query, type, sort, page, pageSize }: KnowledgeCardQuery): KnowledgeCardPage {
  const keyword = query.trim().toLocaleLowerCase();
  const cards = mockCards.map((card) => ({ ...card, ...mockRecordMeta[card.id], detail: mockDetails[card.id] }));

  const matched = cards
    .filter((card) => type === "all" || card.type === type)
    .filter(
      (card) =>
        !keyword ||
        [card.title, card.summary, card.source, ...card.tags].some((value) =>
          value.toLocaleLowerCase().includes(keyword),
        ),
    )
    .toSorted((a, b) => {
      if (sort === "name") return a.title.localeCompare(b.title, "ko");
      const field = sort === "created" ? "createdAt" : "updatedAt";
      return b[field].localeCompare(a[field]);
    });

  return { items: matched.slice((page - 1) * pageSize, page * pageSize), total: matched.length };
}
